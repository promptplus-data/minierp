import { describe, expect, it } from 'vitest';
import { bahtText } from './bahttext';

describe('bahtText', () => {
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [0.5, 'ห้าสิบสตางค์'],
    [1, 'หนึ่งบาทถ้วน'],
    [11, 'สิบเอ็ดบาทถ้วน'],
    [21, 'ยี่สิบเอ็ดบาทถ้วน'],
    [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [121, 'หนึ่งร้อยยี่สิบเอ็ดบาทถ้วน'],
    [121.5, 'หนึ่งร้อยยี่สิบเอ็ดบาทห้าสิบสตางค์'],
    [1.01, 'หนึ่งบาทหนึ่งสตางค์'],
    [0.21, 'ยี่สิบเอ็ดสตางค์'],
    [1000000, 'หนึ่งล้านบาทถ้วน'],
    ['1000021.75', 'หนึ่งล้านยี่สิบเอ็ดบาทเจ็ดสิบห้าสตางค์'],
    [21000000, 'ยี่สิบเอ็ดล้านบาทถ้วน'],
    [-250, 'สองร้อยห้าสิบบาทถ้วน'],
  ])('%s → %s', (n, s) => expect(bahtText(n)).toBe(s));

  it('rounds to the satang without float drift', () => {
    expect(bahtText(1.005)).toBe('หนึ่งบาทหนึ่งสตางค์');
    expect(bahtText('0.995')).toBe('หนึ่งบาทถ้วน');
  });
});
